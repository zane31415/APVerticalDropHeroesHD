"""Emits ap_tables.gml -- the generated half of the in-game AP runtime.

Everything here is derived from defs.py so the GML id tables and the apworld
always agree. Do not hand-edit the output.
"""
import os
import sys

# defs.py is owned by the apworld package -- it is the single source of truth
# for every id, and the apworld imports it directly at generation time. Here we
# reach into that package rather than keeping a second copy that could drift.
# In the shipped patcher bundle there is no apworld directory, so package.py
# drops defs.py in beside this file and the local import wins.
_HERE = os.path.dirname(os.path.abspath(__file__))
for _cand in (_HERE,
              os.path.join(_HERE, "..", "apworld", "vertical_drop_heroes")):
    if os.path.isfile(os.path.join(_cand, "defs.py")):
        sys.path.insert(0, os.path.abspath(_cand))
        break
else:
    sys.exit("defs.py not found (looked in build/ and apworld/vertical_drop_heroes/)")

import defs  # noqa: E402

OUT = os.path.join(_HERE, "..", "gml", "ap_tables.gml")

GROUP_INDEX = {"trait": 0, "power1": 1, "power2": 2}
SHOP_INDEX = {key: i for i, (key, *_r) in enumerate(defs.SHOPS)}


def gml_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    L = []
    a = L.append
    a("// GENERATED by mod/build/gen_gml.py -- do not edit by hand.")
    a("// Lookup tables mapping in-game state to Archipelago ids.")
    a("")
    a(f"global.ap_base_id = {defs.BASE_ID};")
    a(f"global.ap_final_level = {defs.FINAL_LEVEL};")
    a(f"global.ap_max_shop_tier = {defs.MAX_SHOP_TIERS};")
    a("")

    # --- skill locations/items: [group, index] -> id, and name lookup --------
    a("// skill group: 0=trait 1=power1 2=power2")
    for kind, arr, names in defs.SKILL_GROUPS:
        g = GROUP_INDEX[kind]
        a(f"global.ap_skill_count[{g}] = {len(names)};")
    a("")
    # merchant unlock locations, indexed 1..50 in purchase order
    for name, lid, cat, meta in defs.LOCATIONS:
        if cat == "unlock":
            a(f"global.ap_unlock_loc[{meta['order']}] = {lid};")
            a(f"global.ap_unlock_level[{meta['order']}] = {meta['level']};")
    a(f"global.ap_unlock_total = {defs.TOTAL_SKILLS};")
    a(f"global.ap_unlocks_per_level = {defs.UNLOCKS_PER_LEVEL};")
    a(f"global.ap_unlock_levels = {defs.UNLOCK_LEVELS};")
    a("")
    for name, iid, cls, cnt, meta in defs.ITEMS:
        if "skill" not in meta:
            continue
        g = GROUP_INDEX[meta["kind"]]
        a(f"global.ap_skill_item[{g}, {meta['index']}] = {iid};")
    a("")
    # skill name -> (group, index), used by new_unlock / set_merchant
    a("// skill name lookup: parallel arrays, linear scan (50 entries, cold path)")
    n = 0
    for kind, arr, names in defs.SKILL_GROUPS:
        g = GROUP_INDEX[kind]
        for idx, sname in enumerate(names):
            a(f"global.ap_sk_name[{n}] = {gml_str(sname)};")
            a(f"global.ap_sk_group[{n}] = {g};")
            a(f"global.ap_sk_index[{n}] = {idx};")
            n += 1
    a(f"global.ap_sk_total = {n};")
    a("")

    # --- shops ---------------------------------------------------------------
    a("// shops: 0=blacksmith(dlevel) 1=apothecary(hlevel) 2=monk(plevel)")
    for name, lid, cat, meta in defs.LOCATIONS:
        if cat != "shop":
            continue
        s = SHOP_INDEX[meta["shop"]]
        a(f"global.ap_shop_loc[{s}, {meta['tier']}] = {lid};")
    a("")
    for name, iid, cls, cnt, meta in defs.ITEMS:
        if "shop" in meta:
            a(f"global.ap_shop_item[{SHOP_INDEX[meta['shop']]}] = {iid};")
    a("")

    # --- shortcuts -----------------------------------------------------------
    for name, lid, cat, meta in defs.LOCATIONS:
        if cat == "shortcut":
            a(f"global.ap_short_loc[{meta['level']}] = {lid};")
    for name, iid, cls, cnt, meta in defs.ITEMS:
        if meta.get("shortcut"):
            a(f"global.ap_short_item = {iid};")
    a("")

    # --- level clears + goal -------------------------------------------------
    for name, lid, cat, meta in defs.LOCATIONS:
        if cat == "clear":
            a(f"global.ap_clear_loc[{meta['level']}] = {lid};")
        elif cat == "goal":
            a(f"global.ap_goal_loc = {lid};")
    a("")

    # --- filler --------------------------------------------------------------
    for name, iid, cls, cnt, meta in defs.ITEMS:
        if meta.get("filler"):
            a(f"global.ap_filler_item = {iid};")
    a("")
    a(f"global.ap_loc_count = {len(defs.LOCATIONS)};")
    a(f"global.ap_item_id_max = {max(i for _n, i, _c, _ct, _m in defs.ITEMS)};")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(L)} lines)")


if __name__ == "__main__":
    main()
